export function nearestCity(lat: number, lng: number): string {
  let best = CITIES[0]
  let bd = Infinity
  for (const c of CITIES) {
    const d = (c[1] - lat) * (c[1] - lat) + (c[2] - lng) * (c[2] - lng)
    if (d < bd) {
      bd = d
      best = c
    }
  }
  return best[0]
}
